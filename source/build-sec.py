#!/usr/bin/env python3
"""Fills SEC('<stage>',[i,j]) placeholders in RangeKit content templates with the original lesson sections.
Usage: python3 source/build-sec.py            (builds rk-ad.js and rk-lnx.js from their .src.js)"""
import json, re, os, glob
here = os.path.dirname(os.path.abspath(__file__))
secs = {}
for f in glob.glob(os.path.join(here, '*-sections.json')):
    secs.update(json.load(open(f, encoding='utf-8')))
def sub(m):
    sid, idx = m.group(1), [int(x) for x in m.group(2).split(',')]
    return json.dumps(''.join('<h3>%s</h3>%s' % (secs[sid][i]['h'], secs[sid][i]['html']) for i in idx), ensure_ascii=False)
for src in sorted(glob.glob(os.path.join(here, 'rk-*.src.js'))):
    out = re.sub(r"SEC\('(\w+)', ?\[([\d, ]+)\]\)", sub, open(src, encoding='utf-8').read())
    dst = src.replace('.src.js', '.js')
    open(dst, 'w', encoding='utf-8').write('/* GENERATED by build-sec.py from %s — edit that file */\n' % os.path.basename(src) + out)
    print('wrote', os.path.basename(dst), len(out))
