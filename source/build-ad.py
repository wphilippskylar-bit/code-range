#!/usr/bin/env python3
"""Builds source/rk-ad.js from source/rk-ad.src.js by replacing SEC('adN',[i,j]) with the original
lesson sections (source/ad-sections.json, extracted from the pre-RangeKit AD track) as a JS string."""
import json, re, os
here = os.path.dirname(os.path.abspath(__file__))
secs = json.load(open(os.path.join(here, 'ad-sections.json'), encoding='utf-8'))
src = open(os.path.join(here, 'rk-ad.src.js'), encoding='utf-8').read()
def sub(m):
    sid, idx = m.group(1), [int(x) for x in m.group(2).split(',')]
    html = ''.join('<h3>%s</h3>%s' % (secs[sid][i]['h'], secs[sid][i]['html']) for i in idx)
    return json.dumps(html, ensure_ascii=False)
out = re.sub(r"SEC\('(ad\d)', ?\[([\d, ]+)\]\)", sub, src)
open(os.path.join(here, 'rk-ad.js'), 'w', encoding='utf-8').write('/* GENERATED by build-ad.py from rk-ad.src.js — edit the .src.js */\n' + out)
print('wrote rk-ad.js', len(out))
